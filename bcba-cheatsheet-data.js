// nothing is inferred from what another payer requires.
//
// WHAT THAT MEANS WHEN YOU EDIT THIS FILE
//
//   * A payer the cheat sheet leaves empty stays empty. Molina has no
//     treatment-plan components in the document, so it has none here, and the
//     Hub says the cheat sheet does not list any rather than borrowing
//     CareSource's. Filling that gap is a clinical decision for the Clinical
//     Director, made in the cheat sheet, not here.
//   * Payers differ on purpose. NV Medicaid and Anthem BCBS carry a flat list;
//     CareSource, Aetna, TRICARE and SilverSummit carry titled sections. That
//     is how the document is written and it is preserved.
//   * Wording is not tidied. TRICARE's hot buttons include "Including any
//     educational goals", which reads oddly out of context -- it is what the
//     document says, and rewriting a payer requirement is not this file's job.
//
// HOW A SECTION IS CLASSIFIED
//
//   group: "plan"   -- required in the treatment plan
//   group: "reauth" -- the payer's additional requirements for continued
//                      authorization. A section is reauth when its own title
//                      says so, or when it is nested under one that does
//                      (Aetna's Progress / If Progress Is Limited / Parent
//                      Training / Continued Medical Necessity sit under
//                      REAUTHORIZATION REQUIREMENTS).
//   hot_buttons     -- a payer's "Reviewer Hot Buttons" list, kept apart
//                      because it is what a reviewer looks for rather than a
//                      component of the plan. Only Aetna, TRICARE and
//                      SilverSummit have one; the rest show none rather than
//                      being given generic advice.
//
//   kind: "item" is a requirement and gets a checkbox. kind: "lead" is a
//   lead-in line ending in a colon ("Each behavior should include:") -- there
//   is nothing to tick, so it is a label.
//
// Regenerated by converting the document, not by editing this file by hand.

